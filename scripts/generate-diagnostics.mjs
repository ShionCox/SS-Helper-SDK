import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SS_HELPER_DIAGNOSTICS } from '@ss-helper/sdk/errors';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'server-plugin', 'diagnostics.generated.js');
const serverPrefixes = [
  'INTERNAL_ERROR', 'INVALID_PAYLOAD', 'WORKSPACE_', 'SERVER_', 'BACKUP_', 'BRIDGE_', 'HTTP_',
];
const codes = Object.keys(SS_HELPER_DIAGNOSTICS)
  .filter(code => serverPrefixes.some(prefix => code === prefix || code.startsWith(prefix)))
  .sort();
const definitions = Object.fromEntries(codes.map((code) => [
  code,
  { transportCode: SS_HELPER_DIAGNOSTICS[code].transportCode },
]));
const source = `// Generated from @ss-helper/sdk SS_HELPER_DIAGNOSTICS by scripts/generate-diagnostics.mjs.\n`
  + `// Do not edit this file by hand.\n`
  + `export const SERVER_DIAGNOSTICS = Object.freeze(${JSON.stringify(definitions, null, 2)});\n`
  + `export const SERVER_REASON_CODES = Object.freeze(Object.keys(SERVER_DIAGNOSTICS));\n`;
fs.writeFileSync(output, source, 'utf8');
